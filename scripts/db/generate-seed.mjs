// Generate supabase/seed.sql from the committed catalog JSON.
// Usage: node scripts/db/generate-seed.mjs
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const GEN = path.join(ROOT, "src", "data", "generated");
const read = async (f) => JSON.parse(await fs.readFile(path.join(GEN, f), "utf8").catch(() => '{"places":[]}'));

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v == null || Number.isNaN(Number(v)) ? "null" : String(Number(v)));

export const REGIONS = [
  ["north", "ภาคเหนือ", "Northern"],
  ["northeast", "ภาคตะวันออกเฉียงเหนือ", "Northeastern"],
  ["central", "ภาคกลาง", "Central"],
  ["east", "ภาคตะวันออก", "Eastern"],
  ["west", "ภาคตะวันตก", "Western"],
  ["south", "ภาคใต้", "Southern"],
];

export const CATEGORIES = [
  ["national_park", "อุทยานแห่งชาติ", "National park"],
  ["nature", "ธรรมชาติ", "Nature"],
  ["waterfall", "น้ำตก", "Waterfall"],
  ["beach", "ชายหาด", "Beach"],
  ["island", "เกาะ", "Island"],
  ["mountain", "ภูเขา", "Mountain"],
  ["cave", "ถ้ำ", "Cave"],
  ["viewpoint", "จุดชมวิว", "Viewpoint"],
  ["history", "ประวัติศาสตร์", "History"],
  ["museum", "พิพิธภัณฑ์", "Museum"],
  ["temple", "ศาสนสถาน", "Religious site"],
  ["market", "ตลาด", "Market"],
  ["shopping", "แหล่งช้อปปิ้ง", "Shopping"],
  ["park", "สวนสาธารณะ", "Park"],
  ["activity", "กิจกรรม", "Activity"],
  ["restaurant", "ร้านอาหาร", "Restaurant"],
  ["cafe", "คาเฟ่", "Cafe"],
  ["hotel", "โรงแรม", "Hotel"],
  ["hostel", "โฮสเทล", "Hostel"],
  ["guest_house", "เกสต์เฮาส์", "Guest house"],
  ["motel", "โมเต็ล", "Motel"],
  ["apartment", "อพาร์ตเมนต์ให้เช่า", "Serviced apartment"],
];

async function main() {
  const { provinces } = await read("provinces.json");
  const wd = await read("places-wikidata.json");
  const osm = await read("places-osm.json");
  const out = [];
  out.push("-- Generated by scripts/db/generate-seed.mjs — do not edit by hand.");
  out.push("begin;");
  out.push("insert into public.countries (code, name_th, name_en) values ('TH', 'ประเทศไทย', 'Thailand') on conflict (code) do nothing;");
  out.push(
    "insert into public.regions (id, country_code, name_th, name_en) values\n" +
      REGIONS.map(([id, th, en]) => `(${q(id)}, 'TH', ${q(th)}, ${q(en)})`).join(",\n") +
      "\non conflict (id) do update set name_th = excluded.name_th, name_en = excluded.name_en;",
  );
  out.push(
    "insert into public.place_categories (id, name_th, name_en) values\n" +
      CATEGORIES.map(([id, th, en]) => `(${q(id)}, ${q(th)}, ${q(en)})`).join(",\n") +
      "\non conflict (id) do update set name_th = excluded.name_th, name_en = excluded.name_en;",
  );
  out.push(
    "insert into public.provinces (slug, iso_code, country_code, region_id, name_th, name_en, wikidata_id, centroid_lat, centroid_lng) values\n" +
      provinces
        .map(
          (p) =>
            `(${q(p.slug)}, ${q(p.iso)}, 'TH', ${q(p.region)}, ${q(p.nameTh)}, ${q(p.nameEn)}, ${q(p.wikidataId)}, ${n(p.centroid[0])}, ${n(p.centroid[1])})`,
        )
        .join(",\n") +
      "\non conflict (slug) do update set name_th = excluded.name_th, name_en = excluded.name_en, region_id = excluded.region_id;",
  );

  const catIds = new Set(CATEGORIES.map((c) => c[0]));
  // Same rule as the app catalog: an OSM POI tagged with a Wikidata item we already have is a duplicate.
  const wdIds = new Set(wd.places.map((p) => p.source.externalId));
  const osmPlaces = osm.places.filter((p) => !p.wikidataRef || !wdIds.has(p.wikidataRef));
  const places = [...wd.places, ...osmPlaces].filter((p) => catIds.has(p.category));
  const seen = new Set();
  const rows = [];
  for (const p of places) {
    if (seen.has(p.id)) continue;
    seen.add(p.id);
    rows.push(
      `(${q(p.id)}, ${q(p.slug)}, ${q(p.provinceSlug)}, ${q(p.kind)}, ${q(p.category)}, ${q(p.nameTh)}, ${q(p.nameEn)}, ${q(
        p.descriptionTh,
      )}, ${q(p.descriptionEn)}, ${n(p.lat)}, ${n(p.lng)}, ${q(p.website)}, ${q(p.openingHours ?? null)}, ${q(
        p.fee ?? null,
      )}, 'published', 'provider', ${q(p.source.provider)}, ${q(p.source.externalId)}, ${q(p.source.url)}, ${q(
        p.source.license,
      )}, ${q(p.source.attribution)}, ${q(p.source.fetchedAt)})`,
    );
  }
  for (let i = 0; i < rows.length; i += 500) {
    out.push(
      "insert into public.places (id, slug, province_slug, kind, category, name_th, name_en, description_th, description_en, lat, lng, website, opening_hours, fee, status, data_label, provider, external_id, source_url, license, attribution, fetched_at) values\n" +
        rows.slice(i, i + 500).join(",\n") +
        "\non conflict (id) do update set name_th = excluded.name_th, name_en = excluded.name_en, description_th = excluded.description_th, description_en = excluded.description_en, lat = excluded.lat, lng = excluded.lng, website = excluded.website, opening_hours = excluded.opening_hours, fetched_at = excluded.fetched_at;",
    );
  }
  const imgs = places.filter((p) => p.image);
  for (let i = 0; i < imgs.length; i += 500) {
    out.push(
      "insert into public.place_images (place_id, url, author, license, license_url, source_url, review_status) values\n" +
        imgs
          .slice(i, i + 500)
          .map(
            (p) =>
              `(${q(p.id)}, ${q(p.image.url)}, ${q(p.image.author)}, ${q(p.image.license)}, ${q(p.image.licenseUrl)}, ${q(
                p.image.sourceUrl,
              )}, 'approved')`,
          )
          .join(",\n") +
        "\non conflict (place_id, url) do nothing;",
    );
  }
  out.push("commit;");
  await fs.writeFile(path.join(ROOT, "supabase", "seed.sql"), out.join("\n\n") + "\n", "utf8");
  console.log(`seed.sql: ${provinces.length} provinces, ${rows.length} places, ${imgs.length} images`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
